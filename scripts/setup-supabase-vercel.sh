#!/usr/bin/env bash
# ============================================================================
# SIM MADIN — Supabase + Vercel Setup Script
# ============================================================================
# Usage: bash scripts/setup-supabase-vercel.sh
#
# This script will:
#   1. Verify Supabase project access
#   2. Run SQL migration (create storage bucket + policies)
#   3. Run Prisma migration (create all tables)
#   4. Run seed script (create users in Supabase Auth)
#   5. Set Vercel env vars (if VERCEL_TOKEN provided)
#
# Required env vars (set in shell before running):
#   - SUPABASE_ACCESS_TOKEN (sbp_xxx...) — for Supabase CLI
#   - SUPABASE_SERVICE_ROLE_KEY (eyJ...) — for admin Auth API
#   - SUPABASE_DB_PASSWORD — for DATABASE_URL construction
#   - VERCEL_TOKEN (vercel_xxx...) — for Vercel CLI (optional)
#
# Example:
#   export SUPABASE_ACCESS_TOKEN="sbp_xxx..."
#   export SUPABASE_SERVICE_ROLE_KEY="eyJ..."
#   export SUPABASE_DB_PASSWORD="your-password"
#   export VERCEL_TOKEN="vercel_xxx..."
#   bash scripts/setup-supabase-vercel.sh
# ============================================================================
set -euo pipefail

SUPABASE_REF="ooglxextkliuhpequwme"
SUPABASE_URL="https://${SUPABASE_REF}.supabase.co"
ANON_KEY="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6Im9vZ2x4ZXh0a2xpdWhwZXF1d21lIiwicm9sZSI6ImFub24iLCJpYXQiOjE3OTMyMDYyNzUsImV4cCI6MjEwODc4MjI3NX0.os3Vbdo0TB6z4OrH4b3ZLFQqBpNY1pMN-8LKyhZaK2w"

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "SIM MADIN — Supabase + Vercel Setup"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

# ── Verify required env vars ─────────────────────────────────────────────
MISSING=()
[ -z "${SUPABASE_SERVICE_ROLE_KEY:-}" ] && MISSING+=("SUPABASE_SERVICE_ROLE_KEY")
[ -z "${SUPABASE_DB_PASSWORD:-}" ] && MISSING+=("SUPABASE_DB_PASSWORD")

if [ ${#MISSING[@]} -gt 0 ]; then
  echo "❌ Missing required env vars: ${MISSING[*]}"
  echo ""
  echo "Set them before running this script:"
  echo "  export SUPABASE_SERVICE_ROLE_KEY='eyJ...'  # from Supabase Dashboard → API"
  echo "  export SUPABASE_DB_PASSWORD='your-password'  # set when creating project"
  echo ""
  echo "Optional (for Vercel env vars setup):"
  echo "  export VERCEL_TOKEN='vercel_xxx...'  # from https://vercel.com/account/tokens"
  exit 1
fi

echo "✓ All required env vars present"
echo ""

# ── Update .env with Supabase config ────────────────────────────────────
echo "▸ 1/5 Updating .env with Supabase Postgres connection..."
DB_URL="postgresql://postgres.${SUPABASE_REF}:${SUPABASE_DB_PASSWORD}@aws-0-southeast-1.pooler.supabase.com:6543/postgres?pgbouncer=true&connection_limit=1"
DIRECT_URL="postgresql://postgres.${SUPABASE_REF}:${SUPABASE_DB_PASSWORD}@aws-0-southeast-1.supabase.com:5432/postgres"

cat > .env << EOF
# SIM MADIN — Auto-generated by setup script
NEXT_PUBLIC_SUPABASE_URL=${SUPABASE_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${SUPABASE_SERVICE_ROLE_KEY}
DATABASE_URL=${DB_URL}
DIRECT_URL=${DIRECT_URL}
STORAGE_STRICT_MAGIC=true
NODE_ENV=development
EOF
echo "✓ .env updated with Postgres connection string"
echo ""

# ── Run SQL setup (storage bucket + policies) ────────────────────────────
echo "▸ 2/5 Running SQL setup (storage bucket + policies)..."
SQL_FILE="supabase/migrations/01_setup_storage_and_policies.sql"
if [ -f "$SQL_FILE" ]; then
  # Use Supabase REST API with service_role key to execute SQL
  RESPONSE=$(curl -sSL -X POST "${SUPABASE_URL}/rest/v1/rpc/query" \
    -H "apikey: ${SUPABASE_SERVICE_ROLE_KEY}" \
    -H "Authorization: Bearer ${SUPABASE_SERVICE_ROLE_KEY}" \
    -H "Content-Type: application/json" \
    -d "{\"query\": \"$(cat $SQL_FILE | tr '\n' ' ' | sed 's/"/\\"/g')\"}" \
    -w "\n%{http_code}" 2>&1)
  HTTP_CODE=$(echo "$RESPONSE" | tail -1)
  if [ "$HTTP_CODE" = "200" ] || [ "$HTTP_CODE" = "201" ]; then
    echo "✓ SQL executed successfully"
  else
    echo "⚠️  SQL execution via REST API failed (HTTP $HTTP_CODE). Run manually in Supabase SQL Editor."
    echo "   File: $SQL_FILE"
  fi
else
  echo "⚠️  SQL file not found: $SQL_FILE"
fi
echo ""

# ── Run Prisma migration ────────────────────────────────────────────────
echo "▸ 3/5 Running Prisma migration (create all tables in Postgres)..."
npx prisma migrate dev --name init_supabase --skip-seed 2>&1 | tail -10
if [ ${PIPESTATUS[0]} -eq 0 ]; then
  echo "✓ Prisma migration applied successfully"
else
  echo "❌ Prisma migration failed. Check error above."
  exit 1
fi
echo ""

# ── Run seed script ─────────────────────────────────────────────────────
echo "▸ 4/5 Running seed script (create users in Supabase Auth + Prisma DB)..."
npx tsx scripts/seed.ts 2>&1 | tail -20
echo ""

# ── Set Vercel env vars (if token provided) ─────────────────────────────
echo "▸ 5/5 Setting Vercel env vars..."
if [ -z "${VERCEL_TOKEN:-}" ]; then
  echo "⚠️  VERCEL_TOKEN not set. Skipping Vercel env vars setup."
  echo "   Set VERCEL_TOKEN and re-run this script, OR set env vars manually at:"
  echo "   https://vercel.com/mdta01/sim-madin/settings/environment-variables"
else
  # Use Vercel CLI to set env vars
  for ENV_VAR in \
    "NEXT_PUBLIC_SUPABASE_URL=${SUPABASE_URL}" \
    "NEXT_PUBLIC_SUPABASE_ANON_KEY=${ANON_KEY}" \
    "SUPABASE_SERVICE_ROLE_KEY=${SUPABASE_SERVICE_ROLE_KEY}" \
    "DATABASE_URL=${DB_URL}" \
    "DIRECT_URL=${DIRECT_URL}"; do
    KEY="${ENV_VAR%%=*}"
    VALUE="${ENV_VAR#*=}"
    echo "  Setting $KEY..."
    echo "$VALUE" | npx vercel env add "$KEY" production preview development 2>&1 | tail -1
  done
  echo "✓ Vercel env vars set"
fi

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "✅ SETUP COMPLETED"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "Next steps:"
echo "  1. Push to GitHub: git push origin main"
echo "  2. Verify production: https://sim-madin.vercel.app"
echo "  3. Login with: admin@madrasah.test / admin123"
echo ""
